// Diagram generation and the scaffold-diagrams checks (PLAN.md section 10). Pure functions: check.mjs
// reads the files and git, and tests call these directly.
import { parseYaml } from '../lib/config.mjs';

export const START = '<!-- generated by `node packages/core/diagrams/check.mjs --write`: do not edit by hand -->';
export const END = '<!-- end of generated diagram -->';
export const PLAN_SECTIONS = [2, 6, 8];
export const UNCHANGED_LABEL = 'scaffold:diagram-unchanged';

const EDGE = /^(\w+) (?:-- (.+) )?--> (\w+)$/;
const ICON = (emoji) => `<span style='font-size:2em'>${emoji}</span>`;
const SHAPES = {
  human: (t) => `{"${ICON('🧑')}<br/>${t}"}`,
  check: (t) => `{{"${t}"}}`,
  ai: (t) => `["${ICON('🤖')} ${t}"]`,
  state: (t) => `["${t}"]`,
};

export const parseWorkflow = (text) => parseYaml(text);

// Problems in workflow.yml's diagram itself: unknown kinds or owners, bad edges, unreachable nodes.
export function diagramProblems(diagram) {
  const problems = [];
  const nodes = diagram?.nodes ?? {};
  for (const [id, n] of Object.entries(nodes)) {
    if (!SHAPES[n.kind ?? 'state']) problems.push(`node ${id}: unknown kind ${n.kind}`);
    if (!['scaffold', 'manual'].includes(n.owner ?? 'scaffold')) problems.push(`node ${id}: unknown owner ${n.owner}`);
    if (typeof n.text !== 'string' || n.text.includes('"')) problems.push(`node ${id}: text must be set and have no double quotes`);
  }
  const linked = new Set();
  for (const e of diagram?.edges ?? []) {
    const m = String(e).match(EDGE);
    if (!m) { problems.push(`edge "${e}": not "a --> b" or "a -- label --> b"`); continue; }
    for (const id of [m[1], m[3]]) {
      if (!nodes[id]) problems.push(`edge "${e}": unknown node ${id}`);
      linked.add(id);
    }
  }
  for (const id of Object.keys(nodes)) if (!linked.has(id)) problems.push(`node ${id}: not on any edge`);
  return problems;
}

export function currentDiagram(diagram) {
  const nodes = Object.entries(diagram.nodes);
  const byOwner = (o) => nodes.filter(([, n]) => (n.owner ?? 'scaffold') === o).map(([id]) => id).join(',');
  return [
    '```mermaid',
    'flowchart TD',
    '  subgraph key[Key]',
    '    direction LR',
    '    ks[SCAFFOLD]',
    '    km[Manual]',
    `    kh${SHAPES.human('Human<br/>must act')}`,
    `    ka${SHAPES.check('Automated<br/>check')}`,
    `    kai${SHAPES.ai('AI step')}`,
    '    ks ~~~ km ~~~ kh ~~~ ka ~~~ kai',
    '  end',
    '  style key fill:#fff,stroke:#000',
    `  key ~~~ ${nodes[0][0]}`,
    '',
    ...nodes.map(([id, n]) => `  ${id}${SHAPES[n.kind ?? 'state'](n.text)}`),
    '',
    ...diagram.edges.map((e) => {
      const [, from, label, to] = String(e).match(EDGE);
      return label ? `  ${from} -- ${label} --> ${to}` : `  ${from} --> ${to}`;
    }),
    '',
    '  linkStyle default stroke-width:3px',
    '',
    '  classDef scaffold fill:#1e40af,color:#fff',
    '  classDef manual fill:#4b5563,color:#fff',
    '  class ks,kh,ka,kai scaffold',
    '  class km manual',
    `  class ${byOwner('scaffold')} scaffold`,
    `  class ${byOwner('manual')} manual`,
    '```',
  ].join('\n');
}

// Jobs in a workflow file: { name: { needs: [], uses: [] } }. Reads the layout SCAFFOLD's workflows use.
export function workflowJobs(yaml) {
  const jobs = {};
  const body = yaml.split(/^jobs:\n/m)[1] ?? '';
  let current;
  for (const line of body.split('\n')) {
    const job = line.match(/^ {2}([a-z][\w-]*):\s*$/);
    if (job) { current = jobs[job[1]] = { needs: [], uses: [] }; continue; }
    if (!current) continue;
    const needs = line.match(/^ {4}needs:\s*(.+)$/);
    if (needs) current.needs.push(...needs[1].replace(/[[\]]/g, '').split(',').map((s) => s.trim()).filter(Boolean));
    const uses = line.match(/uses:\s*JackWP1\/scaffold\/([^@\s]+)@/);
    if (uses) current.uses.push(uses[1]);
  }
  return jobs;
}

// Event triggers in a caller workflow's `on:` block, as `event.type` (or `event` when it has no types).
export function callerTriggers(yaml) {
  const on = (yaml.split(/^on:\n/m)[1] ?? '').split(/^\S/m)[0];
  const triggers = [];
  for (const [, event, rest] of on.matchAll(/^ {2}([a-z_]+):(.*)$/gm)) {
    const types = on.split(new RegExp(`^ {2}${event}:.*\\n`, 'm'))[1].match(/^ {4}types: \[(.+)\]/);
    if (rest.trim() || !types) triggers.push(event);
    else for (const t of types[1].split(',')) triggers.push(`${event}.${t.trim()}`);
  }
  return triggers;
}

// The Actions graph: caller jobs → reusable workflows → their jobs → package actions.
export function actionsDiagram(caller, workflows) {
  const id = (s) => s.replace(/[^\w]/g, '_');
  const lines = ['```mermaid', 'flowchart LR', '  subgraph caller["Caller: .github/workflows/scaffold.yml"]'];
  const callerJobs = workflowJobs(caller);
  for (const job of Object.keys(callerJobs)) lines.push(`    c_${id(job)}["${job}"]`);
  lines.push('  end');
  const actions = new Set();
  for (const [file, yaml] of Object.entries(workflows)) {
    lines.push(`  subgraph w_${id(file)}["${file}"]`);
    for (const [job, j] of Object.entries(workflowJobs(yaml))) {
      lines.push(`    w_${id(file)}_${id(job)}["${job}"]`);
      for (const n of j.needs) lines.push(`    w_${id(file)}_${id(n)} --> w_${id(file)}_${id(job)}`);
      for (const u of j.uses) actions.add(u);
    }
    lines.push('  end');
  }
  for (const [job, j] of Object.entries(callerJobs)) {
    for (const u of j.uses) lines.push(`  c_${id(job)} --> w_${id(u.split('/').pop())}`);
  }
  for (const [file, yaml] of Object.entries(workflows)) {
    for (const [job, j] of Object.entries(workflowJobs(yaml))) {
      for (const u of [...new Set(j.uses)]) lines.push(`  w_${id(file)}_${id(job)} --> a_${id(u)}["${u}"]`);
    }
  }
  lines.push('```');
  return lines.join('\n');
}

// Replaces the generated block in a Markdown file (between START and END).
export function replaceGenerated(markdown, generated) {
  const [before, rest] = markdown.split(START);
  if (rest === undefined || !rest.includes(END)) throw new Error('no generated block: add the START and END markers');
  return `${before}${START}\n${generated}\n${END}${rest.split(END)[1]}`;
}

// Disagreements between workflow.yml and the implementation.
export function consistencyProblems({ workflow, labels, callerYaml, workflowFiles, skills }) {
  const problems = [...diagramProblems(workflow.diagram)];
  const stages = Object.entries(workflow.stages ?? {});
  const declared = new Set([...(workflow.reserved_labels ?? []), ...stages.flatMap(([, s]) => s.labels ?? [])]);
  for (const l of labels) if (!declared.has(l)) problems.push(`label ${l} is in labels.yml but not in workflow.yml`);
  for (const l of declared) if (!labels.includes(l)) problems.push(`label ${l} is in workflow.yml but not in labels.yml`);

  const triggers = new Set([...(workflow.core?.triggers ?? []), ...stages.flatMap(([, s]) => s.triggers ?? [])]);
  const actual = new Set(callerTriggers(callerYaml));
  for (const t of triggers) if (!actual.has(t)) problems.push(`trigger ${t} is in workflow.yml but not in the caller template`);
  for (const t of actual) if (!triggers.has(t)) problems.push(`trigger ${t} is in the caller template but not in workflow.yml`);

  const callerUses = Object.values(workflowJobs(callerYaml)).flatMap((j) => j.uses).map((u) => u.split('/').pop());
  const expected = [...(workflow.core?.workflows ?? []), ...stages.map(([, s]) => s.workflow)];
  for (const wf of expected) {
    if (!(wf in workflowFiles)) problems.push(`workflow ${wf} is in workflow.yml but not in .github/workflows/`);
    if (!callerUses.includes(wf)) problems.push(`workflow ${wf} is not called by the caller template`);
  }
  for (const wf of Object.keys(workflowFiles)) {
    if (wf !== 'self-test.yml' && !expected.includes(wf)) problems.push(`workflow ${wf} is not in workflow.yml`);
  }
  for (const [name, s] of stages) {
    const uses = Object.values(workflowJobs(workflowFiles[s.workflow] ?? '')).flatMap((j) => j.uses);
    if (uses.some((u) => !u.startsWith(`packages/${name}/`))) problems.push(`${s.workflow} calls actions outside packages/${name}/`);
    for (const skill of s.skills ?? []) if (!skills[name]?.includes(skill)) problems.push(`skill ${skill} is not in packages/${name}/skills/`);
    for (const skill of skills[name] ?? []) if (!(s.skills ?? []).includes(skill)) problems.push(`skill ${skill} in packages/${name}/skills/ is not in workflow.yml`);
  }
  return problems;
}

// PLAN.md split into its numbered `## N.` sections.
function sections(markdown) {
  const out = {};
  for (const part of markdown.split(/^(?=## \d+\. )/m)) {
    const n = part.match(/^## (\d+)\. /)?.[1];
    if (n) out[n] = part;
  }
  return out;
}

// Before code exists: a change to the workflow in PLAN.md sections 2, 6 or 8 must come with a diagram change.
export function planWithoutDiagram({ basePlan, headPlan, changedFiles, labels }) {
  const before = sections(basePlan);
  const after = sections(headPlan);
  const changed = PLAN_SECTIONS.filter((n) => before[n] !== after[n]);
  if (!changed.length) return null;
  if (changedFiles.some((f) => f.startsWith('docs/diagrams/'))) return null;
  if (labels.includes(UNCHANGED_LABEL)) return null;
  return `PLAN.md section${changed.length > 1 ? 's' : ''} ${changed.join(', ')} changed without a change in docs/diagrams/: update the diagrams, or have an approver apply ${UNCHANGED_LABEL}`;
}
